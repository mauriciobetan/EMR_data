II. S.2. Focus group guide (in original Spanish)

A. Introducción
1.	¿Puede decirnos su nombre, su edad, de dónde es originario, cuánto tiempo trabajó (o ha trabajado) en la extracción de guano y su rol en ese trabajo?
2.	¿Cómo empezó a trabajar en el guano?
3.	¿Qué edad tenía cuando empezó este trabajo?
4.	¿De dónde son la mayoría de los trabajadores del guano? 

B. Condiciones de trabajo y vida en las islas
5.	¿Cómo es un día normal de trabajo? Descríbanos desde que se levanta hasta que se duerme.
6.	¿Cuántas horas trabajaba al día?
7.	¿Cuántos días a la semana?  
8.	¿Tenía días de descanso/vacaciones? 
9.	¿Tenía que extraer una cierta cantidad de guano al día?
10.	¿Qué herramientas usaba? 
11.	¿Cuánto tiempo permanecía en las islas por campaña?
12.	¿Tenía contrato? 
13.	¿Cómo era el pago?
14.	¿Cuál es su salario?
15.	¿Era suficiente para cubrir las necesidades suyas y de su familia?  
16.	¿En qué les gusta usar su dinero? 
17.	¿En qué trabajan ahora durante el descanso?
18.	¿Dónde vivían? [dónde dormían, qué tipo de cuartos, camas, piso, descansan bien etc.]
19.	¿Qué comían/bebían? [desayuno, comida, cena] 
20.	¿Quién cocinaba? ¿Les gustaba o faltaba algo?, ¿hay mujeres en las islas?
21.	¿Dónde iban al baño/se bañaban?, ¿se sentían cansados?
22.	¿Cómo era la convivencia entre trabajadores?, ¿había discusiones?, ¿cómo se divertían?

C. Salud y Seguridad
23.	¿Consideran que el trabajo es peligroso? o tiene riesgos? [por qué?/cuáles?]
24.	¿Cuáles son los accidentes o problemas de salud más comunes entre los trabajadores?
25.	¿Era común el consumo de alcohol, cigarrillos, u otras drogas entre los trabajadores?
26.	¿Había ayuda, médico, si alguien se enfermaba/lastimaba?
27.	¿Tenían acceso a equipo de protección?
28.	Antes de empezar este trabajo, tenía algún problema de salud? Si sí, ¿cuál? [escribir en una hoja].
29.	¿Sufrió accidentes en el trabajo o problemas de salud por su trabajo? [escriban primero] 
30.	¿Tiene algún problema de salud actualmente? [escriban primero]
31.	¿Alguna vez sintió estrés, miedo, o ansiedad? [escriban primero] 
32.	¿Qué otros riesgos había? (garrapatas, escorpiones, etc.) ?

D. Reflexiones, comparaciones y ecología
33.	¿Cómo recuerda su tiempo en las islas? ¿Qué le gustaba y qué no le gustaba del trabajo?
34.	¿Recuerda algún día especialmente bueno o malo? ¿Qué pasó?
35.	¿Qué diferencias ve entre el trabajo antes y ahora? 
36.	¿Cómo impactó este trabajo a su familia y su comunidad? [qué piensa su familia] 
37.	Si tuviera un hijo, ¿le daría gusto que esté en este trabajo? ¿Por qué?
38.	¿Qué animales hay en las islas? [escriban primero lista] ¿Cómo interactúan con ellos?
39.	¿Ha cambiado el clima desde que empezó a trabajar en el guano? ¿Cómo? 
40.	¿Cree que la extracción afecta a las aves?


E. Futuro del Guano y Políticas
41.	¿Cree que la extracción de guano continuará? ¿Cuáles son sus mayores retos?, ¿sienten que su trabajo es importante para el Perú y se sienten valorados?
42.	 ¿Dónde acaba el guano que usted extrae de las islas? 
43.	¿Usted o alguien que conozca usa guano? ¿En qué cultivos? 
44.	¿Qué cambiaría de este trabajo? ¿Qué es lo mejor y lo peor? [escriban primero]
45.	Si fuera presidente, ¿qué haría respecto al guano? [escriban primero]
46.	¿Qué les sería más útil saber acerca del guano? ¿Qué les gustaría que se supiera en otros países acerca del trabajo guanero?
47.	Para terminar, ¿hay algo que les gustaría comentarnos que no hayamos preguntado?

Conclusión y gracias. 

S.3. Focus group guide translated to English

A. Introduction
1. Could you tell us your name, age, where you are from, how long did you work (or have worked) in guano extraction, and what your role was/is in that work?
2. How did you start working in guano extraction?
3. How old were you when you began this job?
4. Where are most guano workers from?
B. Working and Living Conditions on the Islands

5. What is a typical workday like? Please walk us through it from the moment you wake up until you go to sleep.
6. How many hours did you work per day?
7. How many days per week?
8. Did you have days off or vacations?
9. Did you have to extract a specific amount of guano per day?
10. What tools did you use?
11. How long did you stay on the islands during each work campaign?
12. Did you have a contract?
13. How were you paid?
14. What was your salary?
15. Was it enough to cover your needs and those of your family?
16. What do you like to spend your money on?
17. What do you do for work now during the off-season or rest period?
18. Where did you live on the islands? Where did you sleep, what were the rooms like (beds, floors), and did you rest well?
19. What did you eat and drink? For breakfast, lunch, and dinner.
20. Who cooked? Did you like the food, or was anything missing? Were there women on the islands?
21. Where did you go to the bathroom or bathe? Did you feel physically exhausted?
22. What was daily life like among the workers? Were there arguments? How did you relax or have fun?

C. Health and Safety
23. Do you consider the job dangerous or risky? Why, and what kinds of risks are there?
24. What were the most common accidents or health problems among workers?
25. Was the consumption of alcohol, cigarettes, or other drugs common among workers?
26. Was there medical assistance if someone got sick or injured?
27. Did you have access to protective equipment?
28. Before starting this job, did you have any health problems? If so, which ones? (Write down first.)
29. Did you suffer any work-related accidents or health problems because of this job? (Write down first.)
30. Do you currently have any health problems? (Write down first.)
31. Did you ever feel stress, fear, or anxiety? (Write down first.)
32. What other risks were there? Ticks, scorpions, etc.?

D. Reflections, Comparisons, and Ecology
33. How do you remember your time on the islands? What did you like and dislike about the work?
34. Do you remember a particularly good or bad day? What happened?
35. What differences do you see between the work in the past and now?
36. How did this work affect your family and your community? What does your family think about it?
37. If you had a child, would you want them to do this work? Why or why not?
38. What animals live on the islands? List them first. How do you interact with them?
39. Has the climate changed since you started working in guano extraction? How?
40. Do you think guano extraction affects the birds?

E. Future of Guano and Policies
41. Do you think guano extraction will continue? What are its biggest challenges? Do you feel your work is important for Peru, and do you feel valued?
42. Where does the guano you extract from the islands end up?
43. Do you, or someone you know, use guano? On what crops?
44. What would you change about this job? What is the best and the worst part of it? (Write down first.)
45. If you were president, what would you do regarding guano? (Write down first.)
46. What would be most useful to know about guano? What would you like people in other countries to know about guano workers and their labor?
47. Finally, is there anything you would like to share with us that we haven’t asked?

Conclusion and thanks.



