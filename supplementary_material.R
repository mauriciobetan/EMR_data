I.	S.1. Interview guide (in original Spanish)

1.	 ¿Cómo se llama, a qué se dedica y desde cuándo trabaja en esta labor?
2.	¿Podría describirme el desarrollo de la industria guanera en el Perú desde fines del siglo XIX, a lo largo del siglo XX, y hasta la actualidad?
3.	¿Cuál es su evaluación de la situación actual del guano en el Perú? 
4.	¿Podría hablarme sobre los efectos del cambio climático en los ecosistemas guaneros?   [e.g. especies afectadas, El Niño, gripe aviar, especies invasoras]
5.	¿Cuál considera que es la mayor amenaza para la extracción guanera hoy en día?
6.	¿Cómo afecta la sobrepesca a la producción guanera? 
7.	¿Cómo afecta el cambio climático a la producción guanera? 
8.	¿Cómo afecta la grive aviar a la producción guanera? 
9.	¿Cómo afectan las campañas de extracción de guano a la producción guanera? 
10.	¿Cómo afecta la presencia de ratas (u otras especies invasoras) en las islas la producción guanera?
11.	¿Podría contarnos sobre la situación de la pesca industrial en el Perú? ¿Qué empresas están involucradas? 
12.	¿Existen cuotas y se respetan? ¿Quiénes son los dueños de estas empresas?
13.	¿Qué puede decirme sobre la gripe aviar en el Perú? ¿Cómo están las poblaciones de aves? ¿Cómo se podría mitigar? [¿Afecta sólo al pelícano o también a otras especies como el piquero, el guanay, el pingüino de Humboldt, etc.?]
14.	¿Cuánto fertilizante sintético importa Perú al año? ¿De dónde? 
15.	Si hay guano, ¿por qué el Perú tiene que importar fertilizante sintético? 
16.	¿Se ha intentado utilizar directamente la anchoveta como fertilizante? ¿Por qué sí o por qué no? 
17.	¿Podría el Perú abastecerse sólo con guano? 
18.	De nuestras conversaciones el año pasado, tengo entendido que el uso del guano está estipulado únicamente para “la agricultura nacional familiar de subsistencia de condiciones críticas”. ¿Es así? 
19.	¿Qué dice la ley peruana al respecto? ¿Dónde se puede consultar?
20.	¿Se exporta el guano? ¿A dónde y en qué proporciones? 
21.	¿Cuáles son los principales cultivos del Perú y en cuáles se aplica el guano?
22.	¿A dónde va exactamente el guano de las islas? ¿Qué suelos fertiliza y en qué regiones? 
23.	Por lo que hablamos el año pasado, entiendo que el guano debería tener un valor mucho más alto. ¿Es así? ¿Se derrocha? ¿Se podría aprovechar mejor?
24.	Si usted fuera presidente, ¿qué haría con respecto al guano?
25.	¿Qué sería útil que se supiera sobre el guano? ¿Qué estudios faltan? ¿Qué le gustaría que se conociera en otros países acerca del guano y el trabajo que usted hace?
26.	Para terminar, ¿hay algo más que le gustaría comentarnos y que no le hayamos preguntado?

Gracias por su tiempo y su disposición.

